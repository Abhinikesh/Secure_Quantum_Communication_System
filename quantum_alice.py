    print("=" * 60)
    print("  quantum_alice.py -- standalone test")
    print("  Using Qiskit AerSimulator (local)")
    print("=" * 60)

    NUM_QUBITS = 16

    alice = QuantumAlice(num_qubits=NUM_QUBITS)
    print(f"\nBackend: {alice.get_backend_info()}\n")

    bits, bases, circuits = alice.encode_all(NUM_QUBITS)

    alice.print_quantum_info(num_show=3)

    print(f"Alice bits  : {bits}")
    print(f"Alice bases : {bases}")
    print(f"Circuits    : {len(circuits)} circuits generated")
    print("\n✅ quantum_alice.py test complete")
